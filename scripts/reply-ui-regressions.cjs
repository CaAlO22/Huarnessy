module.exports = async (preview = false) => {
  const passed = []
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
  const waitFor = async predicate => {
    const start = performance.now()
    while (!predicate()) {
      if (performance.now() - start > 3000) throw new Error('Reply transition timed out')
      await wait(8)
    }
  }
  const check = (condition, name) => { if (!condition) throw new Error(name); passed.push(name) }
  const sessionID = 'benchmark-session'
  const emit = (type, properties) => window.benchEmit(type, properties)
  const snapshot = (messageID, type, text) => emit('message.part.updated', { part: { sessionID, messageID, id: `${messageID}-part`, type, text } })
  const send = async text => {
    const input = document.querySelector('textarea')
    Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(input, text)
    input.dispatchEvent(new Event('input', { bubbles: true }))
    await wait(30)
    Array.from(document.querySelectorAll('button')).find(button => button.textContent.trim() === '发送').click()
    await wait(50)
  }
  await send('等待动效测试')
  const bubble = document.querySelector('.hui-reply-bubble')
  check(bubble?.textContent === '等待回复' && bubble.getBoundingClientRect().width === 108, 'sending immediately shows a compact waiting bubble')
  check(document.querySelectorAll('.hui-reply-bubble').length === 1 && !bubble.querySelector('.hui-md'), 'no empty answer is displayed before the user echo')
  emit('message.updated', { info: { sessionID, id: 'ui-user', role: 'user' } })
  snapshot('ui-user', 'text', '等待动效测试')
  emit('message.updated', { info: { sessionID, id: 'ui-reply', role: 'assistant' } })
  snapshot('ui-reply', 'text', '')
  await wait(50)
  check(document.querySelector('.hui-reply-bubble') === bubble && !bubble.querySelector('.hui-md'), 'metadata and empty parts preserve the same waiting bubble')
  if (preview === true) { await wait(300); return passed }
  const reasoningText = '首条思考内容\n'.repeat(30)
  snapshot('ui-reply', 'reasoning', reasoningText)
  await waitFor(() => bubble.classList.contains('is-label-exit'))
  check(document.querySelector('.hui-reply-bubble') === bubble && bubble.classList.contains('is-label-exit'), 'the first answer reuses the waiting bubble and fades its label first')
  await wait(75)
  check(bubble.getBoundingClientRect().width === 108 && getComputedStyle(bubble.querySelector('.hui-wait-label')).opacity < 1, 'waiting text fades right-to-left while bubble width stays fixed')
  await waitFor(() => bubble.classList.contains('is-condensing'))
  await wait(60)
  check(bubble.getBoundingClientRect().width < 108, 'bubble narrows only after the label has disappeared')
  await waitFor(() => bubble.classList.contains('is-dot-exit'))
  check(Math.abs(bubble.getBoundingClientRect().width - 38) < 1 && !!bubble.querySelector('.hui-wait-orbit'), 'the same bubble becomes a rounded square with the dot centered')
  await waitFor(() => bubble.classList.contains('is-unfolding'))
  check(!bubble.querySelector('.hui-wait-orbit') && !bubble.querySelector('.hui-reasoning'), 'the dot disappears before answer text enters the bubble')
  check(Math.abs(bubble.getBoundingClientRect().height - 38) < 1, 'unfolding keeps the glass surface short instead of painting a tall narrow column')
  await waitFor(() => bubble.classList.contains('is-catching-up'))
  const catchupStarted = performance.now()
  await wait(85)
  const firstLength = bubble.querySelector('.hui-reasoning')?.textContent.length ?? 0
  check(firstLength > 0 && firstLength < reasoningText.length, 'buffered text begins appearing in small increments after the glass transition')
  emit('message.part.delta', { sessionID, messageID: 'ui-reply', partID: 'ui-reply-part', field: 'text', delta: '动画期间新到' })
  await wait(90)
  const nextLength = bubble.querySelector('.hui-reasoning')?.textContent.length ?? 0
  check(nextLength > firstLength && nextLength < reasoningText.length + 6, 'text received during catch-up joins the short reveal without a large burst')
  await waitFor(() => bubble.classList.contains('is-ready'))
  check(performance.now() - catchupStarted < 750 && bubble.querySelector('.hui-reasoning')?.textContent.includes('动画期间新到'), 'the reveal catches up within 750ms without losing live content')
  check(bubble === document.querySelector('.hui-reply-bubble') && !bubble.querySelector('.hui-reply-wait') && bubble.getBoundingClientRect().width > 200, 'the original glass bubble carries the answer after the transition')
  emit('message.part.delta', { sessionID, messageID: 'ui-reply', partID: 'ui-reply-part', field: 'text', delta: '继续流式' })
  await wait(40)
  check(document.querySelector('.hui-reasoning')?.textContent.includes('继续流式') && bubble.classList.contains('is-ready'), 'subsequent deltas render without restarting the entrance animation')
  emit('session.error', { sessionID, error: { message: '测试结束' } })
  await wait(30)
  const oldMarkdown = bubble.querySelector('.hui-md')
  await send('再次发送')
  const nextBubble = document.querySelector('.hui-reply-bubble.is-waiting')
  check(!!nextBubble && document.querySelector('.hui-reasoning')?.textContent.includes('继续流式'), 'a new request shows waiting below the previous reply before its user echo')
  check(oldMarkdown === bubble.querySelector('.hui-md') && oldMarkdown.isConnected, 'sending a new request keeps the previous Markdown DOM mounted')
  emit('message.updated', { info: { sessionID, id: 'ui-next-user', role: 'user' } })
  snapshot('ui-next-user', 'text', '再次发送')
  emit('message.updated', { info: { sessionID, id: 'ui-next-reply', role: 'assistant' } })
  snapshot('ui-next-reply', 'text', '')
  await wait(50)
  check(oldMarkdown === bubble.querySelector('.hui-md') && oldMarkdown.isConnected, 'the user echo does not remount earlier Markdown')
  check(nextBubble === document.querySelector('.hui-reply-bubble.is-waiting'), 'the waiting bubble survives the user echo')
  emit('session.error', { sessionID, error: { message: '等待失败' } })
  await wait(250)
  check(!document.querySelector('.hui-reply-bubble.is-waiting'), 'request errors clear the waiting state')
  for (const messageID of ['ui-user', 'ui-reply', 'ui-next-user', 'ui-next-reply']) emit('message.removed', { sessionID, messageID })
  emit('message.updated', { info: { sessionID, id: 'call-user', role: 'user' } })
  snapshot('call-user', 'text', '测试多次调用')
  emit('message.updated', { info: { sessionID, id: 'call-one', role: 'assistant' } })
  snapshot('call-one', 'reasoning', '第一次思考')
  const call = id => document.querySelector(`.hui-call-block[data-message-id="${id}"]`)
  await waitFor(() => !!call('call-one')?.querySelector('.hui-md'))
  const firstCall = call('call-one')
  const firstMarkdown = firstCall.querySelector('.hui-md')
  check(firstCall.classList.contains('is-active') && !firstCall.querySelector('.hui-call-header'), 'the current answer is not labeled as a step')
  for (const [id, tool] of [['read-one', 'read'], ['read-two', 'read'], ['glob-one', 'glob']]) {
    emit('message.part.updated', { part: { sessionID, messageID: 'call-one', id, type: 'tool', tool, state: { status: 'completed', input: {}, output: '' } } })
  }
  await waitFor(() => firstCall.querySelectorAll('.hui-tool-call').length === 3)
  emit('message.updated', { info: { sessionID, id: 'call-two', role: 'assistant' } })
  await wait(40)
  check(firstCall.classList.contains('is-active') && !firstCall.querySelector('.hui-call-header'), 'empty metadata does not turn the current answer into a step')
  snapshot('call-two', 'reasoning', '第二次思考')
  emit('message.part.updated', { part: { sessionID, messageID: 'call-two', id: 'pic-one', type: 'tool', tool: 'read', state: { status: 'completed', input: { filePath: '/tmp/shot.png' }, output: '', title: 'shot.png', metadata: {}, attachments: [{ id: 'pic-file', type: 'file', mime: 'image/png', url: 'data:image/png;base64,AAAA', filename: 'shot.png' }] } } })
  await waitFor(() => !!call('call-two')?.querySelector('.hui-tool-name.hui-pic-read'))
  check(call('call-two').querySelector('.hui-tool-name.hui-pic-read')?.textContent === 'PicRead', 'an image read tool bubble is labeled PicRead')
  await waitFor(() => call('call-two')?.classList.contains('is-active') && firstCall.querySelector('.hui-call-header')?.getAttribute('aria-expanded') === 'false')
  await waitFor(() => firstCall.getBoundingClientRect().width < document.querySelector('.hui-reply-bubble').getBoundingClientRect().width - 20)
  check(firstCall.querySelector('.hui-call-heading')?.textContent === '步骤 1' && !call('call-two').querySelector('.hui-call-header'), 'only completed earlier calls become numbered steps')
  check(firstMarkdown.isConnected && firstCall.querySelector('.hui-call-reveal').getAttribute('aria-hidden') === 'true', 'a new call folds the previous block without unmounting its Markdown')
  check(!document.querySelector('.hui-reply-bubble').classList.contains('glass') && firstCall.getBoundingClientRect().width < document.querySelector('.hui-reply-bubble').getBoundingClientRect().width - 20, 'steps size to their summary without a shared glass background')
  const stepSummary = firstCall.querySelector('.hui-call-meta')
  check(stepSummary?.textContent.includes('调用了 2次 Read，1次 Glob') && stepSummary.querySelector('[data-tool-color="read"]') && stepSummary.querySelector('[data-tool-color="glob"]'), 'the folded step counts tools and retains their individual colors')
  await wait(550)
  const foldedHeight = firstCall.getBoundingClientRect().height
  check(firstCall.getBoundingClientRect().width < 280 && Math.abs(firstCall.getBoundingClientRect().width - firstCall.querySelector('.hui-call-header').getBoundingClientRect().width) < 2.1, 'the fully folded step and its hover target fit the summary text')
  if (preview === 'steps') return passed
  firstCall.querySelector('button').click()
  await waitFor(() => firstCall.querySelector('button').getAttribute('aria-expanded') === 'true')
  await wait(70)
  const openingHeight = firstCall.getBoundingClientRect().height
  check(openingHeight > foldedHeight && getComputedStyle(firstCall.querySelector('.hui-call-content')).opacity < 1, 'step body and content reveal gradually while opening')
  await wait(550)
  const openHeight = firstCall.getBoundingClientRect().height
  check(openHeight > openingHeight && getComputedStyle(firstCall.querySelector('.hui-tool-call')).opacity === '1', 'step and tool calls finish their expansion without remounting')
  firstCall.querySelector('button').click()
  await wait(70)
  const closingHeight = firstCall.getBoundingClientRect().height
  check(closingHeight < openHeight && closingHeight > foldedHeight, `step panel contracts progressively when folded (${foldedHeight}, ${closingHeight}, ${openHeight})`)
  await wait(550)
  check(Math.abs(firstCall.getBoundingClientRect().height - foldedHeight) < 2 && firstMarkdown.isConnected, 'folded step returns to compact height and preserves Markdown DOM')
  firstCall.querySelector('button').click()
  await wait(550)
  emit('message.part.delta', { sessionID, messageID: 'call-two', partID: 'call-two-part', field: 'text', delta: '继续思考' })
  await wait(40)
  check(firstCall.querySelector('button').getAttribute('aria-expanded') === 'true', 'streamed updates do not override a manually reopened block')
  emit('message.updated', { info: { sessionID, id: 'call-three', role: 'assistant' } })
  snapshot('call-three', 'text', '最终回复')
  await waitFor(() => call('call-two')?.querySelector('button')?.getAttribute('aria-expanded') === 'false' && call('call-three')?.classList.contains('is-active'))
  check(call('call-two').querySelector('.hui-call-meta')?.textContent.includes('1次 PicRead') && call('call-two').querySelector('.hui-pic-read')?.textContent === 'PicRead', 'a folded step counts an image read as PicRead')
  check(!call('call-three').querySelector('.hui-call-header'), 'the final answer remains a normal answer rather than a step')
  check(firstCall.querySelector('button').getAttribute('aria-expanded') === 'true', 'a later call preserves the user’s manual expansion of older blocks')
  const mainPanel = document.querySelector('main.glass')
  const paneBackdrop = mainPanel.querySelector('.hui-chat-pane-backdrop')
  const initialPanelSurface = getComputedStyle(paneBackdrop).backgroundImage
  check(getComputedStyle(firstCall).backgroundImage === getComputedStyle(call('call-three')).backgroundImage, 'steps and current answers share the same glass opacity')
  document.querySelector('button[aria-label="外观设置"]').click()
  await waitFor(() => !!document.querySelector('#hui-panel-transparency'))
  const slider = document.querySelector('#hui-panel-transparency')
  check(!!slider, 'the top settings panel exposes a transparency slider')
  Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(slider, '80')
  slider.dispatchEvent(new Event('input', { bubbles: true }))
  slider.dispatchEvent(new Event('change', { bubbles: true }))
  await waitFor(() => localStorage.getItem('hui.panelTransparency') === '80')
  check(getComputedStyle(paneBackdrop).backgroundImage !== initialPanelSurface, 'the transparency control changes panel surfaces live and saves the choice')
  document.querySelector('#hui-appearance-settings button').click()
  await waitFor(() => localStorage.getItem('hui.panelTransparency') === '55')
  const fontSlider = document.querySelector('#hui-chat-font-size')
  check(!!fontSlider && getComputedStyle(call('call-three').querySelector('.hui-md')).fontSize === '15.5px', 'appearance settings expose the default conversation font size')
  Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(fontSlider, '18')
  fontSlider.dispatchEvent(new Event('input', { bubbles: true }))
  fontSlider.dispatchEvent(new Event('change', { bubbles: true }))
  await waitFor(() => localStorage.getItem('hui.chatFontSize') === '18')
  check(getComputedStyle(call('call-three').querySelector('.hui-md')).fontSize === '18px', 'conversation text resizes live and saves the font size')
  fontSlider.parentElement.querySelector('button').click()
  await waitFor(() => localStorage.getItem('hui.chatFontSize') === '15.5')
  const liquidToggle = document.querySelector('.hui-liquid-toggle')
  const panelFilter = () => {
    const style = getComputedStyle(paneBackdrop)
    return [style.webkitBackdropFilter, style.backdropFilter, style.getPropertyValue('-webkit-backdrop-filter')].filter(Boolean).join(' | ')
  }
  if (!liquidToggle.checked) {
    liquidToggle.click()
    await waitFor(() => localStorage.getItem('hui.liquidGlass') === 'true')
  }
  await waitFor(() => !!call('call-three')?.querySelector('feImage')?.getAttribute('href')?.startsWith('data:image/png'))
  const lensBubble = call('call-three')
  const userBubble = document.querySelector('.hui-user-message')
  check(liquidToggle?.checked && getComputedStyle(mainPanel).backdropFilter === 'none' && !document.querySelector('aside.glass').classList.contains('glass-liquid') && panelFilter().includes('blur(22px)'), 'the pane frost sits behind bubbles instead of blocking their backdrop')
  check(lensBubble.classList.contains('glass-liquid') && userBubble?.classList.contains('glass-liquid') && getComputedStyle(lensBubble).backdropFilter.includes('hui-liquid-'), 'the appearance switch applies refraction to assistant and user bubbles')
  check(lensBubble.querySelectorAll('feDisplacementMap').length === 3 && lensBubble.querySelector('feImage')?.getAttribute('href')?.startsWith('data:image/png'), 'bubble RGB channels sample a generated displacement map')
  check(Number(lensBubble.querySelector('filter').getAttribute('data-rim')) >= Math.min(lensBubble.clientWidth, lensBubble.clientHeight) * .1, 'the bubble lens has a proportional refractive curve')
  const lensImage = new Image()
  lensImage.src = lensBubble.querySelector('feImage').getAttribute('href')
  await lensImage.decode()
  const mapCanvas = document.createElement('canvas')
  mapCanvas.width = lensImage.width
  mapCanvas.height = lensImage.height
  const mapContext = mapCanvas.getContext('2d')
  mapContext.drawImage(lensImage, 0, 0)
  const rimY = Math.max(1, Math.round(Number(lensBubble.querySelector('filter').getAttribute('data-rim')) * lensImage.height / lensBubble.clientHeight / 2))
  const topGreen = mapContext.getImageData(Math.round(lensImage.width / 2), rimY, 1, 1).data[1]
  check(topGreen > 128, 'the top rim samples inward instead of pulling the pane border into the bubble')
  check(getComputedStyle(lensBubble, '::after').backgroundImage.includes('data:image/png'), 'the bubble reflection comes from its surface normals')
  liquidToggle.click()
  await waitFor(() => localStorage.getItem('hui.liquidGlass') === 'false')
  check(!lensBubble.classList.contains('glass-liquid') && !userBubble?.classList.contains('glass-liquid') && panelFilter().includes('blur(22px)'), 'turning refraction off restores plain message surfaces without changing pane blur')
  liquidToggle.click()
  await waitFor(() => localStorage.getItem('hui.liquidGlass') === 'true')
  // A step is animated open over ~460ms. Its lens bitmap must be regenerated
  // while the box grows: a folded (small) map stretched to the widening panel
  // magnifies the low-resolution rim into visible stair-stepping.
  firstCall.querySelector('button').click()
  await wait(550)
  firstCall.querySelector('button').click()
  await wait(120)
  const liveWidth = firstCall.clientWidth
  const liveHeight = firstCall.clientHeight
  const liveMapWidth = Number(firstCall.querySelector('feImage')?.getAttribute('width'))
  const liveMapHeight = Number(firstCall.querySelector('feImage')?.getAttribute('height'))
  check(liveMapWidth / liveWidth > .6 && liveMapHeight / liveHeight > .6, `the step lens regenerates while the panel animates open instead of stretching a folded map (${liveWidth}x${liveHeight} vs ${liveMapWidth}x${liveMapHeight})`)
  await wait(500)
  for (const messageID of ['call-user', 'call-one', 'call-two', 'call-three']) emit('message.removed', { sessionID, messageID })
  Array.from(document.querySelectorAll('button')).find(button => button.title === 'Streaming benchmark').click()
  await wait(100)
  return passed
}
