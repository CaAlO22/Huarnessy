module.exports = async (preview = false) => {
  const passed = []
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
  const waitFor = async predicate => {
    const start = performance.now()
    while (!predicate()) {
      if (performance.now() - start > 3000) throw new Error('Reply transition timed out')
      await wait(8)
    }
  }
  const check = (condition, name) => { if (!condition) throw new Error(name); passed.push(name) }
  const sessionID = 'benchmark-session'
  const emit = (type, properties) => window.benchEmit(type, properties)
  const snapshot = (messageID, type, text) => emit('message.part.updated', { part: { sessionID, messageID, id: `${messageID}-part`, type, text } })
  const send = async text => {
    const input = document.querySelector('textarea')
    Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(input, text)
    input.dispatchEvent(new Event('input', { bubbles: true }))
    await wait(30)
    Array.from(document.querySelectorAll('button')).find(button => button.textContent.trim() === '发送').click()
    await wait(50)
  }
  await send('等待动效测试')
  const bubble = document.querySelector('.hui-reply-bubble')
  check(bubble?.textContent === '等待回复' && bubble.getBoundingClientRect().width === 108, 'sending immediately shows a compact waiting bubble')
  check(document.querySelectorAll('.hui-reply-bubble').length === 1 && !bubble.querySelector('.hui-md'), 'no empty answer is displayed before the user echo')
  emit('message.updated', { info: { sessionID, id: 'ui-user', role: 'user' } })
  snapshot('ui-user', 'text', '等待动效测试')
  emit('message.updated', { info: { sessionID, id: 'ui-reply', role: 'assistant' } })
  snapshot('ui-reply', 'text', '')
  await wait(50)
  check(document.querySelector('.hui-reply-bubble') === bubble && !bubble.querySelector('.hui-md'), 'metadata and empty parts preserve the same waiting bubble')
  if (preview) { await wait(300); return passed }
  const reasoningText = '首条思考内容\n'.repeat(30)
  snapshot('ui-reply', 'reasoning', reasoningText)
  await wait(40)
  check(document.querySelector('.hui-reply-bubble') === bubble && bubble.classList.contains('is-label-exit'), 'the first answer reuses the waiting bubble and fades its label first')
  await wait(75)
  check(bubble.getBoundingClientRect().width === 108 && getComputedStyle(bubble.querySelector('.hui-wait-label')).opacity < 1, 'waiting text fades right-to-left while bubble width stays fixed')
  await waitFor(() => bubble.classList.contains('is-condensing'))
  await wait(60)
  check(bubble.getBoundingClientRect().width < 108, 'bubble narrows only after the label has disappeared')
  await waitFor(() => bubble.classList.contains('is-dot-exit'))
  check(Math.abs(bubble.getBoundingClientRect().width - 38) < 1 && !!bubble.querySelector('.hui-wait-orbit'), 'the same bubble becomes a rounded square with the dot centered')
  await waitFor(() => bubble.classList.contains('is-unfolding'))
  check(!bubble.querySelector('.hui-wait-orbit') && bubble.querySelector('.hui-reasoning')?.textContent.includes('首条思考内容'), 'the dot disappears before the bubble opens for the answer')
  check(Math.abs(bubble.getBoundingClientRect().height - 38) < 1, 'unfolding keeps the glass surface short instead of painting a tall narrow column')
  await waitFor(() => bubble.classList.contains('is-ready'))
  check(bubble === document.querySelector('.hui-reply-bubble') && !bubble.querySelector('.hui-reply-wait') && bubble.getBoundingClientRect().width > 200, 'the original glass bubble carries the answer after the transition')
  emit('message.part.delta', { sessionID, messageID: 'ui-reply', partID: 'ui-reply-part', field: 'text', delta: '继续流式' })
  await wait(40)
  check(document.querySelector('.hui-reasoning')?.textContent.includes('继续流式') && bubble.classList.contains('is-ready'), 'subsequent deltas render without restarting the entrance animation')
  emit('session.error', { sessionID, error: { message: '测试结束' } })
  await wait(30)
  const oldMarkdown = bubble.querySelector('.hui-md')
  await send('再次发送')
  const nextBubble = document.querySelector('.hui-reply-bubble.is-waiting')
  check(!!nextBubble && document.querySelector('.hui-reasoning')?.textContent.includes('继续流式'), 'a new request shows waiting below the previous reply before its user echo')
  check(oldMarkdown === bubble.querySelector('.hui-md') && oldMarkdown.isConnected, 'sending a new request keeps the previous Markdown DOM mounted')
  emit('message.updated', { info: { sessionID, id: 'ui-next-user', role: 'user' } })
  snapshot('ui-next-user', 'text', '再次发送')
  emit('message.updated', { info: { sessionID, id: 'ui-next-reply', role: 'assistant' } })
  snapshot('ui-next-reply', 'text', '')
  await wait(50)
  check(oldMarkdown === bubble.querySelector('.hui-md') && oldMarkdown.isConnected, 'the user echo does not remount earlier Markdown')
  check(nextBubble === document.querySelector('.hui-reply-bubble.is-waiting'), 'the waiting bubble survives the user echo')
  emit('session.error', { sessionID, error: { message: '等待失败' } })
  await wait(250)
  check(!document.querySelector('.hui-reply-bubble.is-waiting'), 'request errors clear the waiting state')
  for (const messageID of ['ui-user', 'ui-reply', 'ui-next-user', 'ui-next-reply']) emit('message.removed', { sessionID, messageID })
  Array.from(document.querySelectorAll('button')).find(button => button.title === 'Streaming benchmark').click()
  await wait(100)
  return passed
}
