import { unified } from 'unified'
import remarkParse from 'remark-parse'
import remarkGfm from 'remark-gfm'
import remarkMath from 'remark-math'
import remarkRehype from 'remark-rehype'
import rehypeKatex from 'rehype-katex'
import rehypeHighlight from 'rehype-highlight'
import rehypeStringify from 'rehype-stringify'
import { defaultUrlTransform } from 'react-markdown'
import type { Root, RootContent } from 'hast'
import type { Nodes as MarkdownNode } from 'mdast'
import type { MarkdownRequest, MarkdownResult, RenderedBlock } from './markdown-types'

// Reuse processors (and highlight language registration) for the worker's lifetime.
const parser = unified().use(remarkParse).use(remarkGfm).use(remarkMath).freeze()
const renderer = unified()
  .use(remarkRehype, { allowDangerousHtml: true })
  .freeze()
const enrichment = unified()
  .use(rehypeKatex)
  .use(rehypeHighlight, { detect: false })
  .freeze()
const serializer = unified().use(rehypeStringify).freeze()
const containers = new Set(['ul', 'ol', 'table', 'thead', 'tbody', 'tr', 'blockquote'])
const voidElements = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'param', 'source', 'track', 'wbr'])
const enriched = new Map<string, { nodes: RootContent[]; size: number }>()
let cacheSize = 0
const serialized = new WeakMap<RootContent, RenderedBlock>()
let nextCacheID = 0
const sentBlocks = new Map<string, Set<number>>()

function packBlocks(id: string, blocks: RenderedBlock[]): RenderedBlock[] {
  const previous = sentBlocks.get(id)
  const current = new Set<number>()
  function pack(block: RenderedBlock): RenderedBlock {
    if (block.children) return { ...block, children: block.children.map(pack) }
    if (block.cacheID == null) return block
    current.add(block.cacheID)
    return previous?.has(block.cacheID) ? { tag: block.tag, cacheID: block.cacheID, reference: true } : block
  }
  const result = blocks.map(pack)
  // Only retain IDs, and only for a bounded number of message parts.
  if (sentBlocks.size >= 64) sentBlocks.delete(sentBlocks.keys().next().value!)
  sentBlocks.set(id, current)
  return result
}

function enrich(node: RootContent): RootContent[] {
  if (node.type !== 'element') return [node]
  if (containers.has(node.tagName)) {
    node.children = node.children.flatMap(enrich) as typeof node.children
    return [node]
  }
  // Cache at paragraph/list-item/code-block granularity, before the expensive
  // plugins. Lists without blank lines also reuse their completed items.
  const key = String(serializer.stringify({ type: 'root', children: [node] }))
  const cached = enriched.get(key)
  if (cached) return cached.nodes
  const result = (enrichment.runSync({ type: 'root', children: [node] }) as Root).children
  if (key.length <= 32768) {
    const size = key.length + JSON.stringify(result).length
    // Bound retained ASTs as well as entry count: math can expand a short source
    // into a large tree, and changing paragraphs must not retain every version.
    if (size <= 8_000_000) {
      while (enriched.size && (enriched.size >= 512 || cacheSize + size > 8_000_000)) {
        const oldest = enriched.keys().next().value!
        cacheSize -= enriched.get(oldest)!.size
        enriched.delete(oldest)
      }
      enriched.set(key, { nodes: result, size })
      cacheSize += size
    }
  }
  return result
}

function makeSafe(node: Root | RootContent): void {
  // Preserve ReactMarkdown's escaped raw HTML and safe-link behavior. Only HTML
  // generated by our own plugins is inserted into the document.
  if (node.type === 'element') {
    for (const key of ['href', 'src', 'cite']) {
      if (node.properties[key] != null) node.properties[key] = defaultUrlTransform(String(node.properties[key]))
    }
  }
  if ('children' in node) {
    node.children = node.children.map(child => child.type === 'raw' ? { type: 'text', value: child.value } : child) as typeof node.children
    for (const child of node.children) makeSafe(child)
  }
}

function serialize(node: RootContent): RenderedBlock {
  const cached = serialized.get(node)
  if (cached) return cached
  // Stable list items and table rows keep their DOM across successive snapshots.
  // React never has to reconcile every KaTeX/highlight span on each delta.
  if (node.type === 'element') {
    const properties: Record<string, unknown> = {}
    for (const [key, value] of Object.entries(node.properties)) {
      if (key === 'style' && typeof value === 'string') {
        properties.style = Object.fromEntries(value.split(';').filter(Boolean).map(rule => {
          const colon = rule.indexOf(':')
          return [rule.slice(0, colon).trim().replace(/-([a-z])/g, (_, letter: string) => letter.toUpperCase()), rule.slice(colon + 1).trim()]
        }))
      } else {
        const name = /^data[A-Z]/.test(key)
          ? key.replace(/[A-Z]/g, letter => '-' + letter.toLowerCase())
          : /^aria[A-Z]/.test(key) ? 'aria-' + key.slice(4).toLowerCase() : key
        properties[name] = Array.isArray(value) ? value.join(' ') : value
      }
    }
    const block: RenderedBlock = {
      tag: node.tagName, properties, propertiesKey: JSON.stringify(properties), cacheID: ++nextCacheID
    }
    if (containers.has(node.tagName)) {
      block.children = node.children.filter(child => child.type !== 'text' || child.value.trim()).map(serialize)
    } else if (!voidElements.has(node.tagName)) {
      block.html = String(serializer.stringify({ type: 'root', children: node.children }))
    }
    serialized.set(node, block)
    return block
  }
  return { tag: 'span', html: String(serializer.stringify({ type: 'root', children: [node] })) }
}

self.onmessage = (event: MessageEvent<MarkdownRequest>) => {
  const request = event.data
  try {
    const tree = parser.parse(request.text)
    let tailBlock: MarkdownNode | undefined = tree
    while (tailBlock && 'children' in tailBlock && tailBlock.children.length
      && !['paragraph', 'heading', 'code', 'table'].includes(tailBlock.type)) tailBlock = tailBlock.children.at(-1)
    let tailKind: MarkdownResult['tailKind'] = tailBlock && ['paragraph', 'heading'].includes(tailBlock.type)
      && !/\n\s*\n\s*$/.test(request.text) ? 'inline' : 'block'
    if (!request.done) {
      // Do not repeatedly highlight an open fence. The final parse highlights it.
      let last: MarkdownNode | undefined = tree
      while (last && 'children' in last && last.children.length) last = last.children.at(-1)
      if (last?.type === 'code') {
        const source = request.text.slice(last.position?.start.offset ?? 0)
        const lines = source.trimEnd().split('\n')
        const opening = lines[0].match(/^\s*(`{3,}|~{3,})/)
        const closing = opening && lines.length > 1 && new RegExp(`^\\s*${opening[1][0]}{${opening[1].length},}\\s*$`).test(lines.at(-1)!)
        if (opening && !closing) {
          last.lang = null
          tailKind = 'code'
        }
      }
    }
    const htmlTree = renderer.runSync(tree) as Root
    htmlTree.children = htmlTree.children.flatMap(enrich)
    makeSafe(htmlTree)
    self.postMessage({ ...request, tailKind, blocks: packBlocks(request.id, htmlTree.children.map(serialize)) } satisfies MarkdownResult)
  } catch (error) {
    self.postMessage({ ...request, blocks: [], error: String(error) } satisfies MarkdownResult)
  }
}
